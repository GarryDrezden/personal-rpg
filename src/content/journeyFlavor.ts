import type { AppThemeId } from '../types/theme';
import { selectForDate } from './selectVariant';

export type JourneyFlavorState = 'intro' | 'current' | 'near' | 'completed' | 'memory';

type ChapterFlavor = Record<JourneyFlavorState, string[]>;

function pick(lines: string[], date: string, family: string, theme: AppThemeId, extra: string): string {
  const candidates = lines.map((text, i) => ({ id: `${family}_${i + 1}`, text }));
  return selectForDate({
    candidates,
    date,
    family,
    theme,
    extra,
  }).text;
}

