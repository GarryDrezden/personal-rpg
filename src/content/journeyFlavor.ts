export function resolveJourneyFlavorState(params: {
  status: 'locked' | 'current' | 'completed';
  progressPercent: number;
}): JourneyFlavorState {
  if (params.status === 'locked') return 'intro';
  if (params.status === 'completed') return 'completed';
  if (params.progressPercent >= 75) return 'near';
  return 'current';
}

export function pickJourneyFlavorLine(params: {
  stageId: string;
  themeId: AppThemeId;
  status: 'locked' | 'current' | 'completed';
  progressPercent: number;
  date: string;
  memory?: boolean;
}): string | null {
  const pack = params.themeId === 'cozy' ? COZY : DF;
  const chapter = pack[params.stageId];
  if (!chapter) return null;
  const state: JourneyFlavorState = params.memory
    ? 'memory'
    : resolveJourneyFlavorState(params);
  const lines = chapter[state];
  if (!lines?.length) return null;
  return pick(
    lines,
    params.date,
    `journey:${params.stageId}:${state}`,
    params.themeId,
    state,
  );
}

