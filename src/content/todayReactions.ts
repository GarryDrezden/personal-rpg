export const TODAY_REACTION_POOLS = { cozy: COZY, darkFantasy: DF } as const;

export function getTodayReactionPool(
  themeId: AppThemeId,
  context: TodayReactionContext,
): PairedContentVariant[] {
  const pack = themeId === 'cozy' ? COZY : DF;
  return pack[context] ?? pack.default;
}

export function pickTodayReaction(params: {
  themeId: AppThemeId;
  context: TodayReactionContext;
  date: string;
}): PairedContentVariant {
  return selectForDate({
    candidates: getTodayReactionPool(params.themeId, params.context),
    date: params.date,
    family: `today:${params.context}`,
    theme: params.themeId,
  });
}

